-- Номер в классе должен быть уникален. До этого уникальность держалась только
-- на проверке в коде: два ученика, вводящие один номер почти одновременно,
-- могли занять его оба, и отчет учителя показал бы две строки с одним номером.
-- Частичный индекс: ученики без класса (зашли «сам по себе») номера не имеют,
-- у них оба поля NULL, и в индекс они не попадают.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_class_number
    ON users (class_id, number_in_class)
    WHERE class_id IS NOT NULL AND number_in_class IS NOT NULL;
