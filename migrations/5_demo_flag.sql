-- Пометка демонстрационных аккаунтов (/demo, /demo_teacher, seed.py).
-- Без нее любой, кто нажал /demo на проде, включая проверяющих, попадает
-- в метрики пилота со сгенерированной историей.
ALTER TABLE users ADD COLUMN is_demo INTEGER NOT NULL DEFAULT 0;

-- Аккаунты, заведенные самим seed.py, узнаются по идентификатору.
UPDATE users SET is_demo = 1 WHERE max_user_id LIKE 'seed-%';

-- Аккаунты, созданные командой /demo до этой миграции, носят настоящий
-- идентификатор из MAX и по нему не отличаются. Но у них есть история
-- задним числом, а живых участников до 25.09.2026 не существовало:
-- пилот стартует в этот день. Поэтому ученик с ответами раньше этой даты —
-- заведомо демонстрационный. Дата зафиксирована намеренно, чтобы миграция
-- осталась верной и когда ее применят на свежей базе через полгода.
UPDATE users SET is_demo = 1
WHERE role = 'student'
  AND id IN (
      SELECT user_id FROM events
      WHERE type = 'answered' AND created_at < '2026-09-25'
  );
